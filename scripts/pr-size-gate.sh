#!/bin/bash
# pr-size-gate.sh — Count a PR's changed lines after exclusions, classify the
# size tier, and decide whether the `size-override` label authorizes a >400 PR.
#
# Accepts the inputs either as files (--numstat-file / --diff-file, the
# `git diff --numstat` and `git diff` output) or as a commit range
# (--base / --head), and never writes a file or touches the network.
#
# Changed lines = additions + deletions over every included file. Excluded
# classes (all matched against a rename's destination path):
#   - lockfiles (exact basename)
#   - generated code by path segment/basename, or by an added
#     `@generated` / `DO NOT EDIT` / `Code generated by` marker line
#   - snapshots
#   - pure file deletions (only when the diff marks the file deleted; a file
#     that merely lost lines still counts its deletions)
#
# Tiers: <=200 auto, 201-400 human, >400 blocked unless a CODEOWNER applied
# `size-override`, which passes the check but never auto-merges.
#
# Usage:
#   scripts/pr-size-gate.sh --numstat-file <path|-> --diff-file <path> [options]
#   scripts/pr-size-gate.sh --base <ref> --head <ref> [options]
#
#   --format text|json       output shape (default: text)
#   --label present|absent   size-override label state (default: absent)
#   --label-actor <login>    actor of the latest size-override labeled event
#   --repo-owner <login>     fallback authority when no CODEOWNERS file exists
#   --codeowners <path>      explicit CODEOWNERS path (default: .github/CODEOWNERS,
#                            CODEOWNERS, docs/CODEOWNERS — first existing wins)
#
# Exit codes: 0 auto/human/override, 1 blocked, 2 usage or input error.
#
# Standards reference:
#   specs/045-pr-size-gate-and-auto-merge/20-acceptance/AC-045-02-*.md
#   specs/045-pr-size-gate-and-auto-merge/20-acceptance/AC-045-03-*.md
#   docs/CI_CD.md §PR Size Gate and Review-Gated Auto-Merge
set -euo pipefail

# shellcheck source=pr-gate-lib.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/pr-gate-lib.sh"

NUMSTAT_FILE=""
DIFF_FILE=""
BASE_REF=""
HEAD_REF=""
FORMAT="text"
LABEL="absent"
LABEL_ACTOR=""
REPO_OWNER=""
CODEOWNERS_ARG=""

die() { printf 'pr-size-gate: %s\n' "$*" >&2; exit 2; }

usage() {
  sed -n '/^# Usage:/,/^# Standards reference:/p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

parse_args() {
  while [ $# -gt 0 ]; do
    case "$1" in
      --numstat-file) NUMSTAT_FILE="${2:-}"; shift 2 ;;
      --diff-file)    DIFF_FILE="${2:-}"; shift 2 ;;
      --base)         BASE_REF="${2:-}"; shift 2 ;;
      --head)         HEAD_REF="${2:-}"; shift 2 ;;
      --format)       FORMAT="${2:-}"; shift 2 ;;
      --label)        LABEL="${2:-}"; shift 2 ;;
      --label-actor)  LABEL_ACTOR="${2:-}"; shift 2 ;;
      --repo-owner)   REPO_OWNER="${2:-}"; shift 2 ;;
      --codeowners)   CODEOWNERS_ARG="${2:-}"; shift 2 ;;
      --help)         usage; exit 0 ;;
      *)              printf 'pr-size-gate: unknown argument: %s\n' "$1" >&2; usage >&2; exit 2 ;;
    esac
  done
}

validate_args() {
  case "$FORMAT" in text|json) ;; *) die "--format must be text or json (got '$FORMAT')" ;; esac
  case "$LABEL" in present|absent) ;; *) die "--label must be present or absent (got '$LABEL')" ;; esac
}

# ── Inputs ───────────────────────────────────────────────────────────────────
# Two exclusive modes: explicit files, or a git commit range. A partial
# selection in either mode is a usage error — the gate never guesses.
load_inputs_from_files() {
  [ -n "$NUMSTAT_FILE" ] && [ -n "$DIFF_FILE" ] || die "--numstat-file and --diff-file are required (or --base and --head)"
  if [ "$NUMSTAT_FILE" = "-" ]; then
    NUMSTAT_TEXT="$(cat)"
  else
    [ -r "$NUMSTAT_FILE" ] || die "cannot read numstat file: $NUMSTAT_FILE"
    NUMSTAT_TEXT="$(cat "$NUMSTAT_FILE")"
  fi
  [ -r "$DIFF_FILE" ] || die "cannot read diff file: $DIFF_FILE"
  DIFF_TEXT="$(cat "$DIFF_FILE")"
}

load_inputs_from_git() {
  [ -n "$BASE_REF" ] && [ -n "$HEAD_REF" ] || die "--base and --head must be given together"
  [ -z "$NUMSTAT_FILE" ] && [ -z "$DIFF_FILE" ] || die "use either --base/--head or --numstat-file/--diff-file, not both"
  NUMSTAT_TEXT="$(git diff --numstat "$BASE_REF" "$HEAD_REF")" || die "git diff --numstat failed for $BASE_REF..$HEAD_REF"
  DIFF_TEXT="$(git diff "$BASE_REF" "$HEAD_REF")" || die "git diff failed for $BASE_REF..$HEAD_REF"
}

load_inputs() {
  if [ -n "$BASE_REF" ] || [ -n "$HEAD_REF" ]; then
    load_inputs_from_git
  else
    load_inputs_from_files
  fi
}

parse_args "$@"
validate_args
load_inputs

# ── Diff facts: pure deletions and generated-code markers, per file ─────────
# One pass over the unified diff yields two line lists keyed by destination
# path. The +++ header line is not an added line, so it never matches a marker.
DIFF_FACTS="$(printf '%s\n' "$DIFF_TEXT" | awk '
  /^diff --git / {
    cur = $0
    sub(/^diff --git a\/.* b\//, "", cur)
    next
  }
  cur == "" { next }
  /^deleted file mode/ { print "deleted=" cur; next }
  /^\+\+\+ \/dev\/null/ { print "deleted=" cur; next }
  /^\+/ && !/^\+\+\+/ {
    if ($0 ~ /@generated|DO NOT EDIT|Code generated by/) print "marker=" cur
  }
')"
DELETED_SET="$(printf '%s\n' "$DIFF_FACTS" | sed -n 's/^deleted=//p')"
MARKER_SET="$(printf '%s\n' "$DIFF_FACTS" | sed -n 's/^marker=//p')"

# ── Path helpers ─────────────────────────────────────────────────────────────
# dest_path <numstat-path> — a rename is counted once, against its destination.
# Handles both git forms: "src/{old => new}/f.ts" and "old/f.ts => new/f.ts".
dest_path() {
  local p="$1"
  case "$p" in
    *'{'*'=>'*'}'*) p="$(printf '%s' "$p" | sed -E 's/\{[^{}]*=> *([^{}]*)\}/\1/')" ;;
  esac
  case "$p" in
    *'=> '*) p="$(printf '%s' "$p" | sed -E 's/^.*=> *//')" ;;
  esac
  printf '%s' "$p"
}

in_list() { # in_list <newline-list> <value>
  [ -n "$1" ] || return 1
  grep -qxF -- "$2" <<< "$1"
}

is_generated_path() {
  local base
  base="$(basename_of "$1")"
  case "/$1/" in */generated/*) return 0 ;; esac
  case "$base" in
    *.generated.*|*.g.dart|*.pb.go|*.pb.cc|*.pb.h|*_pb2.py|*_pb2_grpc.py|*.designer.cs|*.min.js|*.min.css) return 0 ;;
  esac
  return 1
}

is_snapshot() {
  case "/$1/" in */__snapshots__/*) return 0 ;; esac
  case "$(basename_of "$1")" in *.snap|*.snapshot|*.ambr) return 0 ;; esac
  return 1
}

is_excluded() { # is_excluded <destination-path>
  local p="$1"
  if is_lockfile "$(basename_of "$p")"; then return 0; fi
  if is_generated_path "$p"; then return 0; fi
  if is_snapshot "$p"; then return 0; fi
  if in_list "$DELETED_SET" "$p"; then return 0; fi
  if in_list "$MARKER_SET" "$p"; then return 0; fi
  return 1
}

# ── Counting ────────────────────────────────────────────────────────────────
CHANGED=0
EXCLUDED=0

is_binary_field() { [ "$1" = "-" ]; }

require_count() { # <field> <label> <path> — decimal value on stdout
  case "$1" in ''|*[!0-9]*) die "malformed numstat $2: '$1' ($3)" ;; esac
  # Force base 10: a zero-padded field would otherwise be read as octal.
  printf '%s' "$((10#$1))"
}

count_entry() { # <additions> <deletions> <path>
  local adds="$1" dels="$2" path="$3" dest
  dest="$(dest_path "$path")"
  if is_binary_field "$adds" || is_binary_field "$dels"; then
    # Binary entry: contributes 0 and is never an error.
    if is_excluded "$dest"; then EXCLUDED=$((EXCLUDED + 1)); fi
    return 0
  fi
  adds="$(require_count "$adds" additions "$path")"
  dels="$(require_count "$dels" deletions "$path")"
  if is_excluded "$dest"; then
    EXCLUDED=$((EXCLUDED + 1))
  else
    CHANGED=$((CHANGED + adds + dels))
  fi
}

count_changed_lines() {
  local adds dels path
  while IFS=$'\t' read -r adds dels path; do
    [ -n "$path" ] || continue
    count_entry "$adds" "$dels" "$path"
  done <<< "$NUMSTAT_TEXT"
}

count_changed_lines

# ── Override authorization (OPEN-1) ─────────────────────────────────────────
# An individual @user token in CODEOWNERS authorizes; a team handle
# (@org/team) never does. With no CODEOWNERS file, the repository owner does.
codeowners_file() { # → the FIRST existing candidate, or non-zero
  local candidate
  if [ -n "$CODEOWNERS_ARG" ]; then
    if [ -f "$CODEOWNERS_ARG" ]; then printf '%s' "$CODEOWNERS_ARG"; return 0; fi
    return 1
  fi
  for candidate in .github/CODEOWNERS CODEOWNERS docs/CODEOWNERS; do
    if [ -f "$candidate" ]; then printf '%s' "$candidate"; return 0; fi
  done
  return 1
}

authorized_actor() { # authorized_actor <login>
  local actor="$1" file token
  if ! file="$(codeowners_file)"; then
    if [ -n "$actor" ] && [ "$actor" = "$REPO_OWNER" ]; then return 0; fi
    return 1
  fi
  [ -n "$actor" ] || return 1
  while IFS= read -r token; do
    if [ "$token" = "@$actor" ]; then return 0; fi
  done < <(codeowners_tokens "$file")
  return 1
}

# ── Tier and override classification ────────────────────────────────────────
determine_override() {
  OVERRIDE=absent
  if [ "$LABEL" != present ]; then return 0; fi
  if [ "$CHANGED" -le 400 ]; then OVERRIDE=ignored; return 0; fi
  if authorized_actor "$LABEL_ACTOR"; then OVERRIDE=authorized; else OVERRIDE=unauthorized; fi
}

classify_tier() {
  if [ "$CHANGED" -le 200 ]; then
    TIER=auto
  elif [ "$CHANGED" -le 400 ]; then
    TIER=human
  elif [ "$OVERRIDE" = authorized ]; then
    TIER=override
  else
    TIER=blocked
  fi
  if [ "$TIER" = auto ]; then AUTOMERGE=true; else AUTOMERGE=false; fi
}

determine_override
classify_tier

# ── Output ──────────────────────────────────────────────────────────────────
if [ "$FORMAT" = json ]; then
  printf '{"changed":%s,"tier":"%s","automerge":%s,"override":"%s","excluded":%s}\n' \
    "$CHANGED" "$TIER" "$AUTOMERGE" "$OVERRIDE" "$EXCLUDED"
else
  printf 'changed=%s\ntier=%s\nautomerge=%s\noverride=%s\nexcluded=%s\n' \
    "$CHANGED" "$TIER" "$AUTOMERGE" "$OVERRIDE" "$EXCLUDED"
fi

if [ "$TIER" = blocked ]; then exit 1; fi
exit 0
